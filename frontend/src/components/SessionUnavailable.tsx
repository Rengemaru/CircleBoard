import { Note } from "./ui/Note";

// ログイン状態を確かめられなかったときの案内。
//
// /api/session は未ログインでも 401 ではなく 200 + null を返す(docs/api-spec.md §1)。
// つまり例外が飛んだときは「未ログインだと分かった」ではなく「分からなかった」。
// これを未ログイン扱いにすると、通信が一時的に切れただけのログイン中の人に
// 「ログインすると閲覧できます」と出て、ログインし直させることになる(Issue #72)。
//
// ログインボタンは置かない。ログイン画面も同じ API を使うので、繋がっていない
// 状態では押しても同じところで止まる。
export function SessionUnavailable() {
  return (
    <Note tone="danger">
      ログイン状態を確認できませんでした。通信を確認して、ページを再読み込みしてください。
    </Note>
  );
}
